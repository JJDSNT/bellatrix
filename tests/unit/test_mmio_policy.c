#include "cpu/mmio_policy.h"

#define EXPECT(addr, write, expected) \
    do { if (bellatrix_mmio_policy((addr), 2u, (write)) != (expected)) return __LINE__; } while (0)

int main(void)
{
    EXPECT(0x00DFF004u, 0, BELLATRIX_MMIO_PUBLISHED);
    EXPECT(0x00DFF006u, 0, BELLATRIX_MMIO_PUBLISHED);
    EXPECT(0x00DFF018u, 0, BELLATRIX_MMIO_SYNC);
    EXPECT(0x00DFF01Eu, 0, BELLATRIX_MMIO_PUBLISHED);
    EXPECT(0x00DFF024u, 1, BELLATRIX_MMIO_SYNC);
    EXPECT(0x00DFF05Cu, 1, BELLATRIX_MMIO_SYNC);
    EXPECT(0x00DFF05Eu, 1, BELLATRIX_MMIO_SYNC);
    EXPECT(0x00DFF180u, 1, BELLATRIX_MMIO_POSTED);
    EXPECT(0x00DFF0E0u, 1, BELLATRIX_MMIO_POSTED);
    EXPECT(0x00BFE001u, 0, BELLATRIX_MMIO_SYNC);
    EXPECT(0x00BFD100u, 1, BELLATRIX_MMIO_SYNC);
    EXPECT(0x00800000u, 0, BELLATRIX_MMIO_DIRECT);
    return 0;
}
