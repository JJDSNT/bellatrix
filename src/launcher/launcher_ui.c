// ---------------------------------------------------------------------------
// Layout metrics
// ---------------------------------------------------------------------------

uint32_t lui_stride;
uint32_t lui_scale;
uint32_t lui_char;
uint32_t lui_margin_x;
uint32_t lui_title_h;
uint32_t lui_row_h;
uint32_t lui_status_h;
uint32_t lui_visible_rows;

void ui_init_metrics(void)
{
    lui_stride = pitch / 2u;

    lui_scale = fb_width / 640u;
    if (lui_scale < 1u) lui_scale = 1u;
    if (lui_scale > 3u) lui_scale = 3u;

    lui_char     = 8u * lui_scale;
    lui_margin_x = 2u * lui_char;
    lui_title_h  = lui_char + 12u;
    lui_row_h    = lui_char + 4u;
    lui_status_h = lui_char + 6u;

    uint32_t list_h = fb_height - lui_title_h - 4u - lui_status_h;
    lui_visible_rows = list_h / lui_row_h;
    if (lui_visible_rows == 0u) lui_visible_rows = 1u;
}

