// ---------------------------------------------------------------------------
// Drawing primitives
// ---------------------------------------------------------------------------

void fb_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint16_t colour)
{
    for (uint32_t row = 0u; row < h; row++) {
        uint16_t *line = framebuffer + (y + row) * lui_stride + x;
        for (uint32_t col = 0u; col < w; col++) {
            line[col] = colour;
        }
#if BELLATRIX_ENABLE_BTSTACK
        /* Drain the PL011 FIFO into the BT ring buffer after each scanline so
         * that slow framebuffer writes (uncached MMIO) do not create gaps long
         * enough to overflow the 16-byte hardware FIFO and desync the H4 parser. */
        bt_hal_raspi3_drain_fifo();
#endif
    }
}

void fb_putchar(uint32_t px, uint32_t py, char c, uint16_t fg, uint16_t bg)
{
    unsigned idx = 0u;
    if ((unsigned char)c >= 0x20u && (unsigned char)c <= 0x7Eu) {
        idx = (unsigned char)c - 0x20u;
    }

    const uint8_t *glyph = s_font[idx];

    for (unsigned row = 0u; row < 8u; row++) {
        uint8_t bits = glyph[row];
        for (uint32_t sy = 0u; sy < lui_scale; sy++) {
            uint16_t *dst = framebuffer + (py + row * lui_scale + sy) * lui_stride + px;
            for (unsigned col = 0u; col < 8u; col++) {
                uint16_t c = (bits & (0x80u >> col)) ? fg : bg;
                for (uint32_t sx = 0u; sx < lui_scale; sx++) {
                    dst[col * lui_scale + sx] = c;
                }
            }
        }
    }
}

uint32_t fb_puts(uint32_t x, uint32_t y, const char *s, uint16_t fg, uint16_t bg)
{
    while (*s) {
        fb_putchar(x, y, *s, fg, bg);
        x += lui_char;
        s++;
    }
    return x;
}

void fb_puts_centred(uint32_t x0, uint32_t x1, uint32_t y, const char *s,
                     uint16_t fg, uint16_t bg)
{
    uint32_t len = 0u;
    for (const char *p = s; *p; p++) len++;
    uint32_t w   = len * lui_char;
    uint32_t mid = x0 + (x1 - x0) / 2u;
    uint32_t px  = (w < (x1 - x0)) ? (mid - w / 2u) : x0;

    // Fill background for the full row width
    fb_fill_rect(x0, y, x1 - x0, lui_char, bg);
    fb_puts(px, y, s, fg, bg);
}

void draw_message(const char *msg, uint16_t bg_col)
{
    if (!framebuffer) return;

    const uint32_t W = fb_width;
    const uint32_t H = fb_height;

    fb_fill_rect(0, 0, W, H, COL_BG);
    fb_fill_rect(0, H / 2u - (lui_char + 8u), W, 2u * (lui_char + 8u), bg_col);
    fb_puts_centred(0, W, H / 2u - lui_char / 2u, msg, COL_TEXT, bg_col);
}

